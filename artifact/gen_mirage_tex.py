#!/usr/bin/env python3
"""Generate mirage-data.tex (LaTeX data macros) from the REAL deployed-service
evidence report + the microbenchmark results. Mirrors gen_realtraffic_tex.py.
Usage: python3 gen_mirage_tex.py <evidence_report.json> <v5_results.json> <out.tex>
"""
import json
import sys


def main(ev_path, bench_path, out_path):
    ev = json.load(open(ev_path))
    be = json.load(open(bench_path))
    b = ev["benign"]; sl = ev["low_and_slow"]; ov = ev["overt"]
    mix = ev["overall_lane_mix"]
    e1 = be["E1_overhead"]; e2 = be["E2_provenance_verify"]
    lines = [
        "% AUTO-GENERATED by paper/gen_mirage_tex.py from the live myserver",
        "% mirage-service evidence (loopback deployment) -- do not edit by hand.",
        f"\\newcommand{{\\MrgTotal}}{{{ev['total_records']}}}",
        f"\\newcommand{{\\MrgBenignN}}{{{b['requests']}}}",
        f"\\newcommand{{\\MrgBenignShadow}}{{{b['false_shadowed']}}}",
        f"\\newcommand{{\\MrgBenignRate}}{{{b['false_shadow_rate_pct']}}}",
        f"\\newcommand{{\\MrgSlowN}}{{{sl['requests']}}}",
        f"\\newcommand{{\\MrgSlowFirst}}{{{sl['first_shadow_at_call']}}}",
        f"\\newcommand{{\\MrgOvertN}}{{{ov['requests']}}}",
        f"\\newcommand{{\\MrgOvertFirst}}{{{ov['first_shadow_at_call']}}}",
        f"\\newcommand{{\\MrgOvertLeak}}{{{ov['real_leaks_after_containment']}}}",
        f"\\newcommand{{\\MrgLanePrimary}}{{{mix.get('primary',0)}}}",
        f"\\newcommand{{\\MrgLaneThrottled}}{{{mix.get('throttled',0)}}}",
        f"\\newcommand{{\\MrgLaneShadow}}{{{mix.get('shadow',0)}}}",
        f"\\newcommand{{\\MrgLaneDeception}}{{{mix.get('deception',0)}}}",
        f"\\newcommand{{\\MrgOverheadUs}}{{{e1['added_overhead_us']:.1f}}}",
        f"\\newcommand{{\\MrgVerifyMs}}{{{e2['verify_ms']:.1f}}}",
        f"\\newcommand{{\\MrgVerifyChain}}{{{e2['chain_len']}}}",
    ]
    open(out_path, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out_path} ({len(lines)} macros)")


if __name__ == "__main__":
    main(*sys.argv[1:4])
